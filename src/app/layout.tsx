const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
/** "Oct 2026" as "2026-10". */
const isoMonth = (earned: string) => {
  const [m, y] = earned.split(" ");
  return `${y}-${String(MONTHS.indexOf(m) + 1).padStart(2, "0")}`;
};
